module.exports = {
    name: "موتتي",
    cooldowns: 1,
    async execute(api, event) {
        const { threadID } = event;

        const موتات = [
            "ملاريا يابنت الحلال", "انتحار من كتر الحب", "السل اللي جاي من التنهيدة",
            "سكر زيادة من كتر الحلاوة", "حادث سيارة وهو بيصوركي ستوري",
            "سرطان الكبد من الغيرانية", "غرقانة في دموعك", "كورونا بس نسخة 2050",
            "اختناق من كتر الضحك على ميمزك", "احتراق من الهياط", "رصاصة طايشة من حبيبك السابق",
            "زلزال لما شافك بفستان جديد", "ابتلاع زرنيخ عشان خايفة تسمني", "ايدز عاطفي",
            "موت مفاجئ لما شافكِ أونلاين وما رديتي", "سقوط من السطح وهي بتعلق زينة عيد ميلادك"
        ];

        const سنين = Array.from({length: 50}, (_, i) => 2025 + i);
        const شهر = Math.floor(Math.random() * 12) + 1;
        const يوم = Math.floor(Math.random() * 28) + 1; // عشان مفيش 31 في كل الشهور

        const موت = موتات[Math.floor(Math.random() * موتات.length)];
        const سنة = سنين[Math.floor(Math.random() * سنين.length)];

        api.sendMessage(
            `💀 يوووه ياقلبي هتموتي من: ${موت}\n\n` +
            `🪦 التاريخ: ${يوم}/${شهر}/${سنة}\n\n` +
            `استمتعي باللي فاضل يا قمررر 🥺💕`,
            threadID
        );
    }
};